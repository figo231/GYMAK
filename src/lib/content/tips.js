export function tipOfTheDay(dateISO = localISO()) {
  const [y, m, d] = dateISO.split("-").map(Number);
  const dayNum = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  return TIPS[dayNum % TIPS.length];
}
